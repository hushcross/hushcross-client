import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { checkIcons } from './generate-icons.mjs';

const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');
const plan = JSON.parse(await read('twa-manifest.template.json'));
assert.equal(plan.packageId, 'fun.hushcross.app');
assert.equal(plan.host, 'hushcross.fun');
assert.equal(plan.startUrl, '/');
assert.equal(plan.name, 'HushCross');
assert.equal(plan.fallbackType, 'customtabs');
assert.equal(plan.enableNotifications, false);
assert.deepEqual(plan.additionalTrustedOrigins, []);
assert.deepEqual(plan.fingerprints, []);
assert.deepEqual(plan.features, {});
assert.equal(plan.signingKey, undefined);
const gradle = await read('app/build.gradle');
assert.match(gradle, /compileSdk 36/);
assert.match(gradle, /targetSdk 36/);
assert.match(gradle, /buildToolsVersion '35\.0\.0'/);
assert.match(gradle, /signingConfig null/);
assert.match(gradle, /debuggable false/);
assert.match(gradle, /crunchPngs false/);
assert.match(gradle, /androidbrowserhelper:2\.7\.4/);
assert.doesNotMatch(gradle, /storeFile|storePassword|keyPassword|keyAlias|signingConfigs/);
const manifest = await read('app/src/main/AndroidManifest.xml');
assert.match(manifest, /android:allowBackup="false"/);
assert.match(manifest, /android:usesCleartextTraffic="false"/);
assert.doesNotMatch(manifest, /WebView|POST_NOTIFICATIONS|CAMERA|ACCESS_FINE_LOCATION|READ_EXTERNAL_STORAGE|WRITE_EXTERNAL_STORAGE/);
const permissions = [...manifest.matchAll(/<uses-permission android:name="([^"]+)"/g)].map(match => match[1]);
assert.deepEqual(permissions, ['android.permission.INTERNET']);
assert.match(manifest, /FALLBACK_STRATEGY" android:value="customtabs"/);
const launcher = await read('app/src/main/java/fun/hushcross/app/LauncherActivity.java');
assert.match(launcher, /"hushcross\.fun"\.equalsIgnoreCase\(requested\.getHost\(\)\)/);
assert.doesNotMatch(launcher, /Log\.|System\.out|WebView|addJavascriptInterface/);
await checkIcons();
console.log('TWA source configuration and canonical native icons checked. Signing and Digital Asset Links remain pending.');
